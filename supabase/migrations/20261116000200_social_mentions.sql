/*
  Social @mentions in public posts and comments.
  Notifications are generated by trusted database triggers, not client inserts.
*/

alter table public.notifications
  drop constraint if exists notifications_type_check;

alter table public.notifications
  add constraint notifications_type_check
  check (type in ('follow', 'like', 'comment', 'mention', 'reply', 'event_rsvp', 'event_update', 'event_reminder_24h', 'event_reminder_1h', 'event_reminder_15m'));

create or replace function public.create_social_mention_notifications(
  p_body text,
  p_actor_id uuid,
  p_entity_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_body is null or length(p_body) = 0 then
    return;
  end if;

  insert into public.notifications (recipient_id, actor_id, type, entity_id)
  select distinct mentioned.id, p_actor_id, 'mention', p_entity_id
  from regexp_matches(p_body, '(^|[^[:alnum:]_])@([[:alnum:]_]{1,30})', 'g') as mention(match)
  join public.profiles mentioned
    on lower(mentioned.username) = lower(mention.match[2])
  where mentioned.id <> p_actor_id
    and not exists (
      select 1
      from public.notifications existing
      where existing.recipient_id = mentioned.id
        and existing.actor_id = p_actor_id
        and existing.type = 'mention'
        and existing.entity_id = p_entity_id
    );
end;
$$;

create or replace function public.notify_mentions_in_post()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.create_social_mention_notifications(new.body, new.author_id, new.id);
  return new;
end;
$$;

create or replace function public.notify_mentions_in_comment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.create_social_mention_notifications(new.body, new.author_id, new.id);
  return new;
end;
$$;

drop trigger if exists social_post_mentions on public.posts;
create trigger social_post_mentions
after insert or update of body on public.posts
for each row execute function public.notify_mentions_in_post();

drop trigger if exists social_comment_mentions on public.comments;
create trigger social_comment_mentions
after insert or update of body on public.comments
for each row execute function public.notify_mentions_in_comment();

revoke execute on function public.create_social_mention_notifications(text, uuid, uuid) from public, anon, authenticated;
revoke execute on function public.notify_mentions_in_post() from public, anon, authenticated;
revoke execute on function public.notify_mentions_in_comment() from public, anon, authenticated;
